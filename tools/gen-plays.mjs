// Writes the play scripts in tests/native/ that play whole rounds through the
// real UI, from the rules: each word's cells come from src/rules.js on the
// level's seed, and the script walks the cursor there with the arrow keys and
// Enter (as a keyboard player would). The 1.18.0 runtime's play scripts have
// no pointer drag, so drags and swipes across the tiles are played by the
// browser check (tools/browser-play.mjs, at the tiles' window positions from
// tools/board.mjs project()).   node tools/gen-plays.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as content from '../src/content.js';
import * as rules from '../src/rules.js';

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'tests', 'native');

/** Arrow keys from one cell to another (rows first, then columns). */
function walk(from, to) {
  const lines = [];
  const step = (code, n) => { for (let i = 0; i < n; i++) lines.push(`key ${code} 1`, 'frames 1'); };
  const dr = to[0] - from[0], dc = to[1] - from[1];
  step(dr > 0 ? 'ArrowDown' : 'ArrowUp', Math.abs(dr));
  step(dc > 0 ? 'ArrowRight' : 'ArrowLeft', Math.abs(dc));
  return lines;
}
/** Keyboard selection of a word: to its first cell, Enter, to its last, Enter. */
function keyWord(cursor, cells) {
  const a = cells[0], b = cells[cells.length - 1];
  const lines = [...walk(cursor, a), 'key Enter 1', 'frames 2', ...walk(a, b), 'key Enter 1', 'frames 10'];
  return { lines, cursor: b };
}


const header = (lines) => lines.map((l) => `# ${l}`);

// Journey level 1 on a desktop: the tutorial's four lessons, the words by keys, the results.
{
  const def = content.JOURNEY[0];
  const st = rules.createState(def);
  const W = 1280, H = 720;
  const lines = [
    ...header(['Generated by tools/gen-plays.mjs: Journey level 1 on a desktop (the tutorial, words by', 'the arrow keys and Enter), to the results, then the next level.']),
    `# viewport ${W}x${H}`,
    'until 300 Daily Challenge', 'frames 10', 'click =Play', 'until 60 Journey — Level 1', 'frames 10', 'save journey-setup',
    'click =Start', 'until 120 Trace a line', 'frames 150', 'save tutorial',
    'click =Got it', 'until 60 Words run both ways', 'frames 5', 'click =Got it', 'until 60 Eight directions', 'frames 5',
    'click =Got it', 'until 60 Clean streaks', 'frames 5', 'click =Start Playing', 'until 60 Reset Camera', 'frames 30',
  ];
  let cursor = [0, 0];
  st.words.forEach((w, i) => {
    const k = keyWord(cursor, w.cells);
    cursor = k.cursor;
    lines.push(`# ${w.word}`, ...k.lines);
    if (i < st.words.length - 1) lines.push(`until 60 ${i + 1} of ${st.words.length}`);
    if (i === 0) lines.push('frames 20', 'save found-one');
  });
  lines.push('until 120 Board Complete!', 'frames 30', 'expect First Trail', 'save results',
    'click =Next Level', 'until 120 Find 4 words', 'frames 60', 'save level-2',
    'key Escape 1', 'until 60 Resume', 'frames 10', 'click =Leave Round', 'until 60 Daily Challenge', 'frames 5');
  writeFileSync(join(out, 'journey-1.play'), lines.join('\n') + '\n');
}

// The Move Limit challenge on a phone: the drawers, a hint, an invalid line, pause and resume, words by
// keys, the results with the move limit met.
{
  const def = content.challengeDefinition('challenge-moves');
  const st = rules.createState(def);
  const W = 390, H = 844;
  const lines = [
    ...header(['Generated by tools/gen-plays.mjs: the Move Limit challenge on a phone (390 x 844): the Words', 'and Status drawers, a hint, an invalid line, pause, the words by keys, the results.']),
    `# viewport ${W}x${H}`,
    'until 300 Daily Challenge', 'frames 10', 'click =Challenge', 'until 60 Speed Target', 'frames 10',
    'click Move Limit', 'until 60 Challenge — Move Limit', 'frames 10', 'save challenge-setup', 'click =Start', 'until 120 Words', 'frames 120', 'save phone-play',
    'click =Words', 'until 60 Find 6 words', 'frames 10', 'save words-drawer', 'click =Close word list #2', 'frames 10',
    'click =Hint', 'frames 30', 'save hint',
    // An invalid (non-word) line costs a move: the first two cells of the top row.
    'key Enter 1', 'frames 2', 'key ArrowRight 1', 'frames 1', 'key Enter 1', 'frames 20',
    'click =Status', 'until 60 (used 1)', 'frames 10', 'save status-drawer', 'click =Close status #2', 'frames 10',
    'click =Pause', 'until 60 Resume', 'frames 10', 'save paused', 'click =Resume', 'frames 20',
  ];
  let cursor = [0, 1];
  st.words.forEach((w, i) => {
    const k = keyWord(cursor, w.cells);
    cursor = k.cursor;
    lines.push(`# ${w.word}`, ...k.lines);
    if (i < st.words.length - 1) lines.push(`click =Words`, `until 60 ${i + 1} of ${st.words.length}`, 'frames 5', 'click =Close word list #2', 'frames 10');
  });
  lines.push('until 120 Board Complete!', 'frames 30', `expect met move limit (${st.words.length + 1}/8)`, 'save phone-results',
    'click =Menu', 'until 60 Daily Challenge', 'frames 5');
  writeFileSync(join(out, 'challenge-phone.play'), lines.join('\n') + '\n');
}
